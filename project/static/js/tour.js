/* First-visit guided tour — no module dependencies */
(function () {
  var STORAGE_KEY = 'zifExplorer.tutorialSeen';

  function isSeen() { try { return localStorage.getItem(STORAGE_KEY) === '1'; } catch (_) { return false; } }
  function markSeen() { try { localStorage.setItem(STORAGE_KEY, '1'); } catch (_) {} }
  function clearSeen() { try { localStorage.removeItem(STORAGE_KEY); } catch (_) {} }

  /* ── Tour steps ─────────────────────────────────────────────────────── */
  var STEPS = [
    {
      target: null,
      title: 'Welcome to the ZIF Biocomposite Explorer',
      body: 'This platform was built by Ass. Prof. Aleksandar Kondinski (CheMIn Group, TU Graz) as part of his independent work digitalising research workflows. The experimental data was generated by Ms. Xue Chen under Prof. Falcaro and Ass. Prof. Francesco Carraro at the Institute of Physical and Theoretical Chemistry, TU Graz. This short tour covers the key features — about 90 seconds.',
      pos: 'center'
    },
    {
      target: '#plot',
      title: 'The 3D Ternary Diagram',
      body: 'Each sphere represents one measured ZIF formulation. Its position encodes the Metal (zinc), Ligand (2-methylimidazole), and BSA (protein) fractions — each vertex of the triangle equals 100% of that component. The five stacked triangular layers correspond to five total concentration levels from 12.5 to 100 mg·mL⁻¹.',
      pos: 'left'
    },
    {
      target: '#viewModeGroup',
      title: 'View Mode',
      body: 'Switch between 3D Stacked — all five concentration layers displayed simultaneously — and 2D Ternary, which isolates a single layer for precise composition analysis. Use 3D to spot concentration-driven phase trends; use 2D for detailed per-layer work.',
      pos: 'right'
    },
    {
      target: '#dataLayerGroup',
      title: 'Data Layer',
      body: 'Experimental shows the single experimentally collected dataset, automatically processed through the CheMIn workflow. Prediction fills the covered composition space with phase estimates from a Random Forest + Extra Trees ensemble trained on that dataset. Both overlays measured and predicted points simultaneously.',
      pos: 'right'
    },
    {
      target: '#colourBy',
      title: 'Color By',
      body: 'Choose how markers are coloured. Phase shows which crystalline structure formed (Sodalite, Diamondoid, ZIF-C…). Crystallinity, EE, and Loading Capacity reveal quantitative trends. Phase probability maps show the model\'s per-phase confidence across the full composition space.',
      pos: 'right'
    },
    {
      target: '#crystBalance',
      title: 'Filters',
      body: 'Raise Min Crystallinity to keep only more-crystalline materials. Min EE focuses on formulations with better protein encapsulation. The ATR-IR bands ratio minimum retains samples where the protein Amide I band is large relative to the ZIF framework band. Advanced phase filters let you set per-phase probability thresholds.',
      pos: 'right'
    },
    {
      target: '#rightSidebar',
      title: 'Sample Inspector',
      body: 'Click any measured point in the plot to open its full record here. You will see exact composition, crystallinity, phase fractions as a donut chart, the ATR-IR spectrum with band positions, and up to three repeated XRD experiments — each downloadable as a CSV file.',
      pos: 'left'
    },
    {
      target: '#openDocsBtn',
      title: 'About & Search / Predict',
      body: 'The About button opens full scientific documentation, attribution details, and a phase identification guide with a Replay tour link. Search / Predict lets you drop a custom composition marker anywhere in the diagram and query the ML ensemble for phase probability estimates at that formulation.',
      pos: 'bottom'
    }
  ];

  /* ── State ───────────────────────────────────────────────────────────── */
  var S = { step: 0, tooltip: null, overlays: null, spotlight: null };

  /* ── Overlay (4-div spotlight) ───────────────────────────────────────── */
  function buildOverlays() {
    var BG = 'rgba(12,14,20,0.52)';
    var BASE = 'position:fixed;z-index:9000;pointer-events:none;background:' + BG + ';transition:top .22s,left .22s,right .22s,bottom .22s,width .22s,height .22s;';
    var full = document.createElement('div');
    full.style.cssText = BASE + 'inset:0;display:none;';
    document.body.appendChild(full);

    var top   = document.createElement('div'); top.style.cssText   = BASE; document.body.appendChild(top);
    var bot   = document.createElement('div'); bot.style.cssText   = BASE; document.body.appendChild(bot);
    var left  = document.createElement('div'); left.style.cssText  = BASE; document.body.appendChild(left);
    var right = document.createElement('div'); right.style.cssText = BASE; document.body.appendChild(right);
    return { full: full, top: top, bot: bot, left: left, right: right };
  }

  function showOverlay(rect) {
    var ov = S.overlays;
    var BG = 'rgba(12,14,20,0.52)';
    var BASE = 'position:fixed;z-index:9000;pointer-events:none;background:' + BG + ';transition:top .22s,left .22s,right .22s,bottom .22s,width .22s,height .22s;';

    if (!rect) {
      /* Welcome step — cover whole screen */
      ov.full.style.cssText = BASE + 'inset:0;';
      ['top','bot','left','right'].forEach(function (k) { ov[k].style.cssText = BASE + 'width:0;height:0;'; });
      return;
    }
    ov.full.style.cssText = BASE + 'width:0;height:0;';

    var PAD = 8;
    var W   = window.innerWidth;
    var H   = window.innerHeight;
    var t   = Math.max(0, rect.top    - PAD);
    var b   = Math.min(H, rect.bottom + PAD);
    var l   = Math.max(0, rect.left   - PAD);
    var r   = Math.min(W, rect.right  + PAD);
    var mh  = (b - t);

    ov.top.style.cssText   = BASE + 'top:0;left:0;right:0;height:' + t + 'px;';
    ov.bot.style.cssText   = BASE + 'top:' + b + 'px;left:0;right:0;bottom:0;';
    ov.left.style.cssText  = BASE + 'top:' + t + 'px;left:0;width:' + l + 'px;height:' + mh + 'px;';
    ov.right.style.cssText = BASE + 'top:' + t + 'px;left:' + r + 'px;right:0;height:' + mh + 'px;';
  }

  function hideOverlay() {
    var ov = S.overlays;
    if (!ov) return;
    var GONE = 'position:fixed;z-index:9000;pointer-events:none;width:0;height:0;';
    ['full','top','bot','left','right'].forEach(function (k) { ov[k].style.cssText = GONE; });
  }

  function removeOverlays() {
    var ov = S.overlays;
    if (!ov) return;
    ['full','top','bot','left','right'].forEach(function (k) { ov[k].remove(); });
    S.overlays = null;
  }

  /* ── Spotlight ring (fixed div, not box-shadow on target) ────────────── */
  /* Using a separate fixed element avoids clipping by overflow:hidden on   */
  /* sidebar/container elements like #rightSidebar.                         */
  function buildSpotlight() {
    var el = document.createElement('div');
    el.id = 'tourSpotlight';
    el.className = 'tour-spotlight';
    document.body.appendChild(el);
    return el;
  }

  function showSpotlight(rect) {
    var sp = S.spotlight;
    if (!sp) return;
    var PAD = 5;
    sp.style.left   = Math.max(0, rect.left   - PAD) + 'px';
    sp.style.top    = Math.max(0, rect.top    - PAD) + 'px';
    sp.style.width  = (rect.width  + PAD * 2) + 'px';
    sp.style.height = (rect.height + PAD * 2) + 'px';
    sp.style.borderRadius = '8px';
    sp.classList.add('tour-spotlight--active');
  }

  function hideSpotlight() {
    var sp = S.spotlight;
    if (!sp) return;
    sp.classList.remove('tour-spotlight--active');
  }

  function removeSpotlight() {
    if (S.spotlight) { S.spotlight.remove(); S.spotlight = null; }
  }

  /* ── Tooltip DOM ─────────────────────────────────────────────────────── */
  function buildTooltip() {
    var el = document.createElement('div');
    el.id = 'tourTooltip';
    el.className = 'tour-tooltip';
    el.setAttribute('role', 'dialog');
    el.setAttribute('aria-live', 'polite');
    el.innerHTML =
      '<div class="tour-counter" id="tourCounter"></div>' +
      '<div class="tour-title"   id="tourTitle"></div>' +
      '<div class="tour-body"    id="tourBody"></div>' +
      '<div class="tour-actions">' +
        '<button class="tour-skip" id="tourSkip" type="button">Skip tour</button>' +
        '<div class="tour-nav">' +
          '<button class="tour-back" id="tourBack" type="button">Back</button>' +
          '<button class="tour-next" id="tourNext" type="button">Next</button>' +
        '</div>' +
      '</div>';
    document.body.appendChild(el);
    document.getElementById('tourSkip').addEventListener('click', end);
    document.getElementById('tourBack').addEventListener('click', function () { goTo(S.step - 1); });
    document.getElementById('tourNext').addEventListener('click', function () { goTo(S.step + 1); });
    document.addEventListener('keydown', onKey);
    return el;
  }

  /* ── Navigation ──────────────────────────────────────────────────────── */
  function goTo(idx) {
    if (idx >= STEPS.length) { end(); return; }
    if (idx < 0) return;
    S.step = idx;

    var step = STEPS[idx];
    var n    = STEPS.length;
    var last = idx === n - 1;

    document.getElementById('tourCounter').textContent = 'Step ' + (idx + 1) + ' of ' + n;
    document.getElementById('tourTitle').textContent   = step.title;
    document.getElementById('tourBody').textContent    = step.body;
    document.getElementById('tourNext').textContent    = last ? 'Done ✓' : 'Next →';
    document.getElementById('tourBack').style.visibility = idx === 0 ? 'hidden' : '';

    hideSpotlight();
    placeTooltip(step);

    if (!S.tooltip.classList.contains('tour-visible')) {
      S.tooltip.classList.add('tour-visible');
    }
  }

  /* ── Positioning ─────────────────────────────────────────────────────── */
  function inViewport(rect) {
    return rect.width > 0 && rect.height > 0 &&
           rect.top  >= 0 && rect.left >= 0 &&
           rect.bottom <= (window.innerHeight || 600) &&
           rect.right  <= (window.innerWidth  || 800);
  }

  function placeTooltip(step) {
    var tt  = S.tooltip;
    var W   = window.innerWidth;
    var H   = window.innerHeight;
    var TW  = 326;
    var TH  = 270;
    var GAP = 16;
    var PAD = 14;

    var targetEl = step.target ? document.querySelector(step.target) : null;
    var rect     = targetEl ? targetEl.getBoundingClientRect() : null;
    var visible  = rect && inViewport(rect);

    /* Overlay */
    showOverlay(visible ? rect : null);

    /* Spotlight ring on target — fixed div, not class on element */
    if (visible && targetEl) {
      showSpotlight(rect);
    }

    /* Tooltip position */
    if (!visible || step.pos === 'center') {
      tt.style.left = Math.round((W - TW) / 2) + 'px';
      tt.style.top  = Math.round((H - TH) / 2) + 'px';
      return;
    }

    var l, t;
    var pos = step.pos || 'right';

    if (pos === 'right') {
      l = rect.right + GAP;
      if (l + TW > W - PAD) l = rect.left - TW - GAP;
      t = rect.top + rect.height / 2 - TH / 2;
    } else if (pos === 'left') {
      l = rect.left - TW - GAP;
      if (l < PAD) l = rect.right + GAP;
      t = rect.top + rect.height / 2 - TH / 2;
    } else if (pos === 'bottom') {
      l = rect.left + rect.width / 2 - TW / 2;
      t = rect.bottom + GAP;
      if (t + TH > H - PAD) t = rect.top - TH - GAP;
    } else {
      l = rect.left + rect.width / 2 - TW / 2;
      t = rect.top - TH - GAP;
      if (t < PAD) t = rect.bottom + GAP;
    }

    tt.style.left = Math.max(PAD, Math.min(l, W - TW - PAD)) + 'px';
    tt.style.top  = Math.max(PAD, Math.min(t, H - TH - PAD)) + 'px';
  }

  /* ── Keyboard ────────────────────────────────────────────────────────── */
  function onKey(e) {
    if (!S.tooltip) return;
    if (e.key === 'Escape')     end();
    if (e.key === 'ArrowRight') goTo(S.step + 1);
    if (e.key === 'ArrowLeft')  goTo(S.step - 1);
  }

  /* ── Cleanup ─────────────────────────────────────────────────────────── */
  function end() {
    hideSpotlight();
    removeSpotlight();
    hideOverlay();
    removeOverlays();
    if (S.tooltip) { S.tooltip.remove(); S.tooltip = null; }
    document.removeEventListener('keydown', onKey);
    markSeen();
  }

  /* ── Public API (for replay button in About modal) ───────────────────── */
  function start() {
    if (S.tooltip) return;
    S.overlays  = buildOverlays();
    S.spotlight = buildSpotlight();
    S.tooltip   = buildTooltip();
    goTo(0);
  }

  window.__zifTour = {
    start: start,
    reset: clearSeen
  };

  /* ── Auto-start on first visit ───────────────────────────────────────── */
  if (!isSeen()) {
    setTimeout(start, 1200);
  }
})();
